-- =====================================================================
-- ПРЕДСТАВЛЕНИЕ: баланс подотчёта по сотрудникам
-- =====================================================================
-- Приложение читает его как таблицу employee_cash_balance
-- (фильтр по employee_id, сортировка по name).
-- =====================================================================
create or replace view employee_cash_balance as
select
    e.id   as employee_id,
    e.name as name,
    coalesce(sum(
        case
            when o.operation_type = 'issue'   then  o.amount
            when o.operation_type = 'expense' then -o.amount
            when o.operation_type = 'return'  then -o.amount
            else 0
        end
    ), 0)::numeric as balance
from employees e
left join cash_operations o on o.employee_id = e.id
group by e.id, e.name;

