-- ЗАЧЕМ ЭТОТ ФАЙЛ
-- ---------------
-- Приложение регистрирует сотрудника по email и паролю (js/auth.js → signUp)
-- и НИКАКИХ писем не отправляет и не ждёт. Но если в проекте Supabase
-- включена опция Confirm email (Authentication → Sign In / Providers → Email),
-- то после регистрации сессии не будет: аккаунт создаётся, но остаётся
-- неподтверждённым, и вход падает с ошибкой
--
--     Email not confirmed
--
-- (в приложении это сообщение видно как «Email не подтверждён. Обратитесь
-- к администратору (Email not confirmed)»).
--
-- Правильное лечение — выключить Confirm email в настройках проекта.
-- Этот файл — «скорая помощь» для аккаунтов, которые уже так застряли:
-- подтверждаем их вручную, чтобы люди могли войти сегодня, не дожидаясь
-- изменения настроек.
--
-- КАК ВЫПОЛНИТЬ
-- -------------
--   Supabase → SQL Editor → New query → вставить нужный блок → Run.
--   Блоки независимы: сначала посмотрите список (блок 1), затем правьте.
--
-- ВАЖНО
-- -----
--   * Колонку confirmed_at трогать НЕЛЬЗЯ: в auth.users это вычисляемая
--     колонка (LEAST(email_confirmed_at, phone_confirmed_at)), и Postgres
--     откажет в записи. Подтверждение ставится в email_confirmed_at.
--   * Эти запросы идут в служебную схему auth и требуют прав владельца
--     проекта — выполняются только в SQL Editor. Во фронтенде такого быть
--     не может: у anon-ключа этих прав нет и не должно быть.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. ПОСМОТРЕТЬ, КТО НЕ ПОДТВЕРЖДЁН
-- ---------------------------------------------------------------------
-- email_confirmed_at is null   → вход по паролю невозможен, пока включён
--                                Confirm email;
-- last_sign_in_at is null      → сотрудник ни разу не входил.
select email,
       created_at,
       email_confirmed_at,
       last_sign_in_at
  from auth.users
 order by created_at desc;


-- ---------------------------------------------------------------------
-- 2. ПОДТВЕРДИТЬ ОДИН АККАУНТ (например, fin5@example.com)
-- ---------------------------------------------------------------------
-- Условие email_confirmed_at is null защищает уже подтверждённые записи:
-- повторный запуск ничего не меняет.
update auth.users
   set email_confirmed_at = now()
 where email = 'fin5@example.com'
   and email_confirmed_at is null;


-- ---------------------------------------------------------------------
-- 3. ПОДТВЕРДИТЬ ВСЕ ЗАСТРЯВШИЕ АККАУНТЫ СРАЗУ
-- ---------------------------------------------------------------------
-- Безопасно запускать повторно — «под нож» попадают только неподтверждённые.
update auth.users
   set email_confirmed_at = now()
 where email_confirmed_at is null;

-- Проверка: должно остаться 0.
select count(*) as unconfirmed
  from auth.users
 where email_confirmed_at is null;


-- ---------------------------------------------------------------------
-- 4. КТО ЕЩЁ НЕ ПРИВЯЗАН К СОТРУДНИКУ (это отдельная причина отказа)
-- ---------------------------------------------------------------------
-- Подтверждённый вход сам по себе доступа к данным не даёт: приложение
-- пускает сотрудника только если аккаунт привязан и активен
-- (employees.user_id заполнен, employees.status = 'active'). Такие аккаунты
-- привязывает Администратор в разделе «Сотрудники» → «Привязать аккаунт»
-- (employee_id = null в выборке ниже как раз про них).
--
-- Отдельный случай: если в базе вообще нет активного Администратора
-- с заполненным user_id, приложение включает bootstrap — первый вошедший
-- получает полный доступ, чтобы можно было настроить систему.
select u.email,
       u.email_confirmed_at,
       e.id     as employee_id,
       e.name   as employee_name,
       e.position,
       e.status
  from auth.users u
  left join employees e on e.user_id = u.id
 order by (e.id is null) desc, u.created_at desc;
