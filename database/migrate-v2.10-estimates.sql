-- SQL Editor останавливается на ПЕРВОЙ ошибке, а сообщения об ошибках видны
-- только на вкладке Notices. Поэтому файл заканчивается проверкой того, что
-- реально нужно приложению: 14 таблиц, включённый RLS, закрытая от anon
-- схема, закрытая ПРЯМАЯ запись в смету и пять команд с фиксированным
-- search_path. Строки 'ok' должны повторяться при каждом запуске файла.
do $$
declare
    v_list    text[] := array[
        'estimate_units', 'estimate_work_sections', 'estimate_material_sections',
        'estimate_works', 'estimate_materials', 'estimate_work_materials',
        'estimate_clients', 'estimate_company', 'estimates', 'estimate_sections',
        'estimate_items', 'estimate_item_materials', 'estimate_limits',
        'estimate_command_log'];
    v_names   text[] := array[
        'save_estimate', 'delete_estimate', 'set_estimate_status',
        'estimate_next_number', 'rsk_is_estimate_editor'];
    v_tables  integer;
    v_rls     integer;
    v_funcs   integer;
    v_paths   integer;
    v_anon    integer;
    v_writes  integer;
    v_dep     integer;
begin
    select count(*), count(*) filter (where c.relrowsecurity)
      into v_tables, v_rls
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      cross join unnest(v_list) as t(name)
     where n.nspname = 'public'
       and c.relkind = 'r'
       and c.relname = t.name;

    raise notice 'таблицы смет (справочники, смета, журнал): %',
        case when v_tables = 14 then 'ok'
             else 'MISSING - создано ' || v_tables || ' из 14 таблиц' end;

    raise notice 'RLS включён на таблицах смет: %',
        case when v_rls = 14 then 'ok'
             else 'MISSING - RLS включён на ' || v_rls || ' из 14 таблиц' end;

    select count(*) into v_anon
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      cross join unnest(v_list) as t(name)
     where n.nspname = 'public'
       and c.relkind = 'r'
       and c.relname = t.name
       and has_table_privilege('anon', c.oid, 'SELECT, INSERT, UPDATE, DELETE');

    raise notice 'таблицы смет закрыты от anon: %',
        case when v_anon = 0 then 'ok'
             else 'MISSING - anon имеет права на ' || v_anon || ' таблиц' end;

    select count(*) into v_writes
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      cross join unnest(v_list) as t(name)
     where n.nspname = 'public'
       and c.relkind = 'r'
       and c.relname = t.name
       and t.name in ('estimates', 'estimate_sections', 'estimate_items',
                      'estimate_item_materials', 'estimate_limits',
                      'estimate_command_log')
       and has_table_privilege('authenticated', c.oid, 'INSERT, UPDATE, DELETE');

    raise notice 'смета пишется только командами (прямой insert/update закрыт): %',
        case when v_writes = 0 then 'ok'
             else 'MISSING - прямая запись открыта на ' || v_writes || ' таблиц сметы' end;

    select count(*), count(*) filter (where p.proconfig is not null)
      into v_funcs, v_paths
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
      cross join unnest(v_names) as t(name)
     where n.nspname = 'public'
       and p.proname = t.name;

    raise notice 'команды смет (сохранение, удаление, статус, номер, проверка права): %',
        case when v_funcs = 5 then 'ok'
             else 'MISSING - найдено ' || v_funcs || ' из 5 команд' end;

    raise notice 'у команд смет фиксированный search_path: %',
        case when v_paths = 5 then 'ok'
             else 'MISSING - search_path задан у ' || v_paths || ' из 5 команд' end;

    select count(*) into v_dep
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
      cross join unnest(array[
          'rsk_current_employee_role', 'rsk_current_employee_id']) as t(name)
     where n.nspname = 'public'
       and p.proname = t.name;

    -- Обе функции берутся из v2.7.0: роль решает, кому открыт раздел, а id
    -- записывается автором сметы. Без второй смета не сохраняется вообще —
    -- и ошибка вылезала бы только при нажатии «Сохранить».
    raise notice 'зависимости v2.7.0 (роль и сотрудник): %',
        case when v_dep = 2 then 'ok'
             else 'MISSING - нет rsk_current_employee_role или rsk_current_employee_id: сначала примените database/migrate-v2.7-rls-finance.sql' end;
end $$;

