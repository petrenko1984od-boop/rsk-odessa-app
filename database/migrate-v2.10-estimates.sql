-- =====================================================================
-- FREEDOM — СМЕТЫ (конструктор смет для ПТО)
-- Версия: 2.10.0
-- =====================================================================
-- Что делает эта миграция:
--   1. справочники сметы — работы, материалы, их разделы и единицы
--      измерения, нормы расхода материалов на работу (работа → материалы);
--   2. клиенты (заказчики) и реквизиты своей компании — для документов;
--   3. сами сметы: разделы → позиции → материалы позиции + лимитированные
--      расходы и ПДВ;
--   4. RLS: читать и править может только тройка ролей, которой открыт
--      модуль (Администратор, Главный инженер, Инженер ПТО) — то же право
--      manage_estimate, что и у блока «📊 Смета объекта»;
--   5. команды базы: номер сметы и транзакционное сохранение сметы целиком.
--
-- ПОЧЕМУ НОМЕР И СОХРАНЕНИЕ — В БАЗЕ. Смета сохраняется не одной строкой, а
-- агрегатом (разделы, позиции, материалы, лимиты). Если сохранять это из
-- браузера по частям, обрыв сети посреди операции оставит смету «половинкой»:
-- разделы без позиций. Поэтому запись идёт одной командой базы в транзакции,
-- а номер выдаётся под блокировкой — иначе двое, нажавшие «Создать смету»
-- одновременно, получат одинаковый номер (колонка number уникальна).
--
-- ЗАВИСИМОСТИ: public.rsk_current_employee_role() и
-- public.rsk_current_employee_id() из database/migrate-v2.7-rls-finance.sql —
-- если она не применена, сначала выполните её. Первая решает, кому открыт
-- раздел (Администратор, Главный инженер, Инженер ПТО), вторая записывается
-- автором сметы; без второй смета не сохранится вообще.
--
-- Файл можно запускать повторно: таблицы создаются через if not exists,
-- политики сначала удаляются, функции заменяются.
-- =====================================================================

begin;

-- =====================================================================
-- 1. СПРАВОЧНИК ЕДИНИЦ ИЗМЕРЕНИЯ
-- =====================================================================

create table if not exists public.estimate_units (
    id          bigint generated by default as identity primary key,
    name        text        not null unique,     -- 'м²'
    full_name   text,                            -- 'метр квадратний'
    order_index integer     not null default 0,
    created_at  timestamptz not null default now()
);


-- =====================================================================
-- 2. РАЗДЕЛЫ СПРАВОЧНИКОВ (дерево: «Покрівля» → «Покрівля скатна»)
-- =====================================================================
-- Два одинаковых по структуре дерева: разделы работ и разделы материалов.
-- Отдельные таблицы, а не одна с признаком вида: так ссылки из работ и
-- материалов остаются простыми (section_id → одна понятная таблица).

create table if not exists public.estimate_work_sections (
    id           bigint generated by default as identity primary key,
    name         text        not null,
    parent_id    bigint      references public.estimate_work_sections(id) on delete cascade,
    order_index  integer     not null default 0,
    created_at   timestamptz not null default now()
);

create table if not exists public.estimate_material_sections (
    id           bigint generated by default as identity primary key,
    name         text        not null,
    parent_id    bigint      references public.estimate_material_sections(id) on delete cascade,
    order_index  integer     not null default 0,
    created_at   timestamptz not null default now()
);

-- =====================================================================
-- 3. СПРАВОЧНИК РАБОТ
-- =====================================================================
-- price_worker  — «наряд»: сколько получает исполнитель за единицу;
-- price_client  — «кошторис»: сколько платит заказчик за единицу.
-- Разница и есть прибыль по работе, поэтому обе цены обязательны.

create table if not exists public.estimate_works (
    id           bigint generated by default as identity primary key,
    name         text        not null,
    unit         text        not null default 'шт',
    price_worker numeric     not null default 0,
    price_client numeric     not null default 0,
    description  text,
    section_id   bigint      references public.estimate_work_sections(id) on delete set null,
    created_at   timestamptz not null default now()
);

-- =====================================================================
-- 4. СПРАВОЧНИК МАТЕРИАЛОВ
-- =====================================================================
-- price_purchase        — «наряд»: цена закупки (себестоимость);
-- price_client          — «кошторис»: цена заказчику;
-- is_customer_supplied  — давальческий: привозит заказчик, в суммы не входит.

create table if not exists public.estimate_materials (
    id                   bigint generated by default as identity primary key,
    name                 text        not null,
    unit                 text        not null default 'шт',
    price_purchase       numeric     not null default 0,
    price_client         numeric     not null default 0,
    is_customer_supplied boolean     not null default false,
    section_id           bigint      references public.estimate_material_sections(id) on delete set null,
    created_at           timestamptz not null default now()
);

-- =====================================================================
-- 5. НОРМЫ РАСХОДА: СКОЛЬКО МАТЕРИАЛА НУЖНО НА ЕДИНИЦУ РАБОТЫ
-- =====================================================================
-- consumption — расход материала на 1 единицу работы (например, 0.02 т
-- цемента на 1 м² стяжки). По этим нормам смета сама подставляет материалы
-- в позицию и пересчитывает их количество от объёма работы.

create table if not exists public.estimate_work_materials (
    id          bigint generated by default as identity primary key,
    work_id     bigint  not null references public.estimate_works(id) on delete cascade,
    material_id bigint  not null references public.estimate_materials(id) on delete cascade,
    consumption numeric not null default 0,
    created_at  timestamptz not null default now(),
    unique (work_id, material_id)
);

-- =====================================================================
-- 6. КЛИЕНТЫ (ЗАКАЗЧИКИ) И РЕКВИЗИТЫ СВОЕЙ КОМПАНИИ
-- =====================================================================
-- Клиенты — отдельный справочник, а не поле «объект»: у одного заказчика
-- бывает несколько объектов, и в документах нужны его реквизиты.
-- Реквизиты компании — ровно одна строка (id = 1): их печатают шапкой
-- кошториса и наряда, поэтому в смете они не дублируются.

create table if not exists public.estimate_clients (
    id         bigint generated by default as identity primary key,
    name       text        not null,
    phone      text,
    email      text,
    address    text,
    notes      text,
    created_at timestamptz not null default now()
);

create table if not exists public.estimate_company (
    id            bigint primary key default 1 check (id = 1),
    company_name  text,
    phone         text,
    email         text,
    website       text,
    address       text,
    default_notes text,
    updated_at    timestamptz not null default now()
);

-- =====================================================================
-- 7. СМЕТА: РАЗДЕЛЫ → ПОЗИЦИИ → МАТЕРИАЛЫ ПОЗИЦИИ + ЛИМИТЫ
-- =====================================================================
-- projects (необязательно) — объект стройки: смета привязывается к нему,
-- чтобы план из сметы можно было перенести в разделы объекта (план-факт).
-- Позиция хранит СВОИ цены (price_worker/price_client), а не только ссылку
-- на справочник: справочник меняется со временем, а смета заказчику — это
-- документ, её суммы не должны «поехать» от правки прайса.

create table if not exists public.estimates (
    id                    bigint generated by default as identity primary key,
    number                text        not null unique,      -- '00001/2026'
    number_year           integer     not null,
    number_seq            integer     not null,
    title                 text        not null,
    object_name           text,
    project_id            bigint      references public.projects(id) on delete set null,
    client_id             bigint      references public.estimate_clients(id) on delete set null,
    notes                 text,
    vat_percent           numeric     not null default 0,
    vat_base              text        not null default 'both',   -- works | materials | both
    status                text        not null default 'draft',  -- draft | approved | archived
    created_by_employee_id bigint     references public.employees(id) on delete set null,
    created_at            timestamptz not null default now(),
    updated_at            timestamptz not null default now(),
    -- Итоги сметы. Считает их save_estimate() один раз при сохранении: списку
    -- смет нужны суммы, а тянуть ради этого все разделы, позиции и материалы
    -- каждой сметы — десятки лишних запросов на один экран.
    --   total_client    — сумма к оплате заказчиком (работы + материалы +
    --                     лимиты + ПДВ);
    --   total_materials — материалы по кошторисным ценам (без давальческих);
    --   total_naryad    — наша себестоимость (работы + закупка материалов);
    --   items_count     — сколько позиций в смете.
    total_client          numeric     not null default 0,
    total_materials       numeric     not null default 0,
    total_naryad          numeric     not null default 0,
    items_count           integer     not null default 0
);

create table if not exists public.estimate_sections (
    id          bigint generated by default as identity primary key,
    estimate_id bigint  not null references public.estimates(id) on delete cascade,
    name        text    not null,
    order_index integer not null default 0
);

create table if not exists public.estimate_items (
    id           bigint generated by default as identity primary key,
    section_id   bigint  not null references public.estimate_sections(id) on delete cascade,
    work_id      bigint  references public.estimate_works(id) on delete set null,
    name         text    not null,
    unit         text    not null default 'шт',
    quantity     numeric not null default 0,
    price_worker numeric not null default 0,
    price_client numeric not null default 0,
    order_index  integer not null default 0
);

create table if not exists public.estimate_item_materials (
    id                   bigint generated by default as identity primary key,
    item_id              bigint  not null references public.estimate_items(id) on delete cascade,
    material_id          bigint  references public.estimate_materials(id) on delete set null,
    name                 text    not null,
    unit                 text    not null default 'шт',
    quantity             numeric not null default 0,
    price_purchase       numeric not null default 0,
    price_client         numeric not null default 0,
    consumption          numeric,
    is_customer_supplied boolean not null default false,
    order_index          integer not null default 0
);

create table if not exists public.estimate_limits (
    id          bigint generated by default as identity primary key,
    estimate_id bigint  not null references public.estimates(id) on delete cascade,
    name        text    not null,
    percent     numeric not null default 0,
    base        text    not null default 'both',   -- works | materials | both
    order_index integer not null default 0
);

-- Журнал команд сметы: защита от двойного нажатия «Сохранить». Ключ запроса
-- приходит из браузера (db.newCommandKey), повтор возвращает прежний
-- результат вместо второй сметы.
create table if not exists public.estimate_command_log (
    command_key uuid primary key,
    estimate_id bigint,
    created_at  timestamptz not null default now()
);

-- =====================================================================
