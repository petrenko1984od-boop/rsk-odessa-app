-- =====================================================================
-- Смета читается целиком (разделы → позиции → материалы): это десятки строк,
-- но по ним идут соединения, поэтому внешние ключи индексируем — иначе
-- Postgres сканирует таблицы целиком на каждый уровень вложенности.
-- Отдельные индексы — под списки: сметы объекта, поиск по названию
