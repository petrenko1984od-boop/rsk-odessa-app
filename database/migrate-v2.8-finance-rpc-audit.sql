-- 0. ПРЕДВАРИТЕЛЬНЫЕ ПРОВЕРКИ
-- =====================================================================

do $$
begin
    if to_regprocedure('public.rsk_current_employee_id()') is null
       or to_regprocedure('public.rsk_current_employee_role()') is null then
        raise exception using
            errcode = 'P0001',
            message = 'Сначала примените database/migrate-v2.7-rls-finance.sql';
    end if;

    if to_regclass('public.orders') is null
       or to_regclass('public.order_items') is null
       or to_regclass('public.cash_requests') is null
       or to_regclass('public.cash_request_items') is null
       or to_regclass('public.cash_operations') is null then
        raise exception using
            errcode = 'P0001',
            message = 'Не найдены таблицы заявок/операций — сверьте database/schema.sql';
    end if;
end $$;

-- У одной заявки может быть только один расход своей доставки. Исторические
-- дубли автоматически не удаляем: это финансовые данные, их надо сверить.
do $$
declare
    duplicate_orders text;
begin
    select string_agg(order_id::text, ', ' order by order_id)
      into duplicate_orders
      from (
          select order_id
          from public.cash_operations
          where source = 'own_delivery'
            and order_id is not null
          group by order_id
          having count(*) > 1
      ) as duplicates;

    if duplicate_orders is not null then
        raise exception using
            errcode = 'P0001',
            message = 'Найдены дубли own_delivery для orders.id: ' || duplicate_orders,
            hint = 'Сверьте операции вручную и оставьте одну запись на заявку, затем повторите миграцию.';
    end if;
end $$;

create unique index if not exists cash_operations_one_own_delivery_per_order
    on public.cash_operations (order_id)
    where source = 'own_delivery' and order_id is not null;

