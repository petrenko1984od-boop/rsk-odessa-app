create table if not exists public.audit_log (
    id                  bigint generated by default as identity primary key,
    occurred_at         timestamptz not null default clock_timestamp(),
    actor_user_id       uuid        not null,
    actor_employee_id   bigint      references public.employees(id) on delete set null,
    actor_role          text,
    action              text        not null,
    entity_type         text        not null,
    entity_id           text,
    idempotency_key     uuid        not null,
    old_data            jsonb,
    new_data            jsonb,
    metadata            jsonb       not null default '{}'::jsonb,
    transaction_id      bigint      not null default txid_current()
);

create unique index if not exists audit_log_command_once
    on public.audit_log (actor_user_id, action, idempotency_key);
create index if not exists audit_log_occurred_at_idx
    on public.audit_log (occurred_at desc);
create index if not exists audit_log_actor_idx
    on public.audit_log (actor_employee_id, occurred_at desc);
create index if not exists audit_log_entity_idx
    on public.audit_log (entity_type, entity_id, occurred_at desc);

alter table public.audit_log enable row level security;
alter table public.audit_log force row level security;

revoke all on table public.audit_log from public, anon, authenticated;
grant select on table public.audit_log to authenticated;

-- Identity sequence не выдаём authenticated: журнал пишет только definer-функция.

drop policy if exists rsk_audit_log_select on public.audit_log;
create policy rsk_audit_log_select
on public.audit_log
for select
to authenticated
using (
    public.rsk_current_employee_id() is not null
    and public.rsk_current_employee_role() in ('Администратор', 'Директор')
);

-- Внутренняя запись журнала. Клиент не получает EXECUTE.
create or replace function public.rsk_write_audit(
    p_action          text,
    p_entity_type     text,
    p_entity_id       text,
    p_idempotency_key uuid,
    p_old_data        jsonb,
    p_new_data        jsonb,
    p_metadata        jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    audit_id bigint;
begin
    if auth.uid() is null then
        raise exception using errcode = '28000', message = 'Требуется авторизация';
    end if;

    if p_idempotency_key is null then
        raise exception using errcode = '22023', message = 'idempotency_key обязателен';
    end if;

    insert into public.audit_log (
        actor_user_id,
        actor_employee_id,
        actor_role,
        action,
        entity_type,
        entity_id,
        idempotency_key,
        old_data,
        new_data,
        metadata
    ) values (
        auth.uid(),
        public.rsk_current_employee_id(),
        public.rsk_current_employee_role(),
        p_action,
        p_entity_type,
        p_entity_id,
        p_idempotency_key,
        p_old_data,
        p_new_data,
        coalesce(p_metadata, '{}'::jsonb)
    )
    returning id into audit_id;

    return audit_id;
end;
$$;

revoke all on function public.rsk_write_audit(text, text, text, uuid, jsonb, jsonb, jsonb)
    from public, anon, authenticated;

