    ));

    select a.new_data -> 'result'
      into previous_result
      from public.audit_log as a
     where a.actor_user_id = current_user_id
       and a.action = action_name
       and a.idempotency_key = p_idempotency_key;
    if previous_result is not null then
        return previous_result;
    end if;

    if p_project_id is null or not exists (
        select 1 from public.projects as p where p.id = p_project_id
    ) then
        raise exception using errcode = '22023', message = 'Объект не найден';
    end if;
    if employee_role = 'Прораб' and not exists (
        select 1 from public.projects as p
        where p.id = p_project_id and p.foreman_id = employee_id
    ) then
        raise exception using errcode = '42501', message = 'Прораб может создавать заявки только по своему объекту';
    end if;
    if p_section_id is null or not exists (
        select 1 from public.sections as s
        where s.id = p_section_id and s.project_id = p_project_id
    ) then
        raise exception using errcode = '22023', message = 'Раздел не принадлежит выбранному объекту';
    end if;
    if p_items is null or jsonb_typeof(p_items) <> 'array' then
        raise exception using errcode = '22023', message = 'Позиции должны быть JSON-массивом';
    end if;

    item_count := jsonb_array_length(p_items);
    if item_count < 1 or item_count > 200 then
        raise exception using errcode = '22023', message = 'В заявке должно быть от 1 до 200 позиций';
    end if;

    for item in select value from jsonb_array_elements(p_items)
    loop
        if jsonb_typeof(item) <> 'object' then
            raise exception using errcode = '22023', message = 'Каждая позиция должна быть объектом';
        end if;

        item_name := btrim(coalesce(item ->> 'name', ''));
        item_unit := btrim(coalesce(item ->> 'unit', 'м²'));
        begin
            item_qty := (item ->> 'qty')::numeric;
            item_price := (item ->> 'unit_price')::numeric;
        exception when others then
            raise exception using errcode = '22023', message = 'Количество и цена позиции должны быть числами';
        end;

        if item_name = '' or char_length(item_name) > 500 then
            raise exception using errcode = '22023', message = 'Название позиции обязательно и не длиннее 500 символов';
        end if;
        if item_unit = '' or char_length(item_unit) > 20 then
            raise exception using errcode = '22023', message = 'Некорректная единица измерения';
        end if;
        if item_qty::text in ('NaN', 'Infinity', '-Infinity')
           or item_qty <= 0 or item_qty > 1000000000 then
            raise exception using errcode = '22023', message = 'Количество позиции должно быть больше нуля';
        end if;
        if item_price::text in ('NaN', 'Infinity', '-Infinity')
           or item_price <= 0 or item_price > 1000000000000 then
            raise exception using errcode = '22023', message = 'Цена позиции должна быть больше нуля';
        end if;

        item_qty := round(item_qty, 6);
        item_price := round(item_price, 2);
        item_total := round(item_qty * item_price, 2);
        total_sum := round(total_sum + item_total, 2);

        if item_total <= 0 or total_sum > 1000000000000000 then
            raise exception using errcode = '22023', message = 'Некорректная итоговая сумма заявки';
        end if;

        normalized_items := normalized_items || jsonb_build_array(jsonb_build_object(
            'name', item_name,
            'unit', item_unit,
            'qty', item_qty,
            'unit_price', item_price,
            'total_price', item_total
        ));
    end loop;

    current_year := extract(year from current_date)::integer;
    year_short := right(current_year::text, 2);

    perform pg_advisory_xact_lock(hashtextextended('rsk:cash-request-number:' || current_year::text, 0));

    number_pattern := '^Ф-([0-9]+)/' || year_short || '$';
    select coalesce(max((matched.parts)[1]::bigint), 0)
      into max_number
      from public.cash_requests as r
      cross join lateral (
          select regexp_match(r.request_number, number_pattern) as parts
      ) as matched
     where matched.parts is not null
       and r.created_at >= make_date(current_year, 1, 1)
       and r.created_at < make_date(current_year + 1, 1, 1);

    request_number := format('Ф-%s/%s', max_number + 1, year_short);

    insert into public.cash_requests (
        request_number,
        project_id,
        section_id,
        employee_id,
        total_sum,
        comment,
        status
    ) values (
        request_number,
        p_project_id,
        p_section_id,
        employee_id,
        total_sum,
        nullif(btrim(coalesce(p_comment, '')), ''),
        'pending'
    )
    returning * into created_request;

    insert into public.cash_request_items (
        request_id, name, unit, qty, unit_price, total_price
    )
    select
        created_request.id,
        rows.name,
        rows.unit,
        rows.qty,
        rows.unit_price,
        rows.total_price
    from jsonb_to_recordset(normalized_items) as rows(
        name text, unit text, qty numeric, unit_price numeric, total_price numeric
    );

    result := jsonb_build_object(
        'request_id', created_request.id,
        'request_number', created_request.request_number,
        'status', created_request.status,
        'total_sum', created_request.total_sum,
        'items_count', item_count
    );

    perform public.rsk_write_audit(
        action_name,
        'cash_requests',
        created_request.id::text,
        p_idempotency_key,
        null,
        jsonb_build_object(
            'result', result,
            'request', to_jsonb(created_request),
            'items', normalized_items
        ),
        jsonb_build_object('project_id', p_project_id, 'section_id', p_section_id)
    );

    return result;
end;
$$;

-- =====================================================================
-- 4. RPC: ISSUE_CASH_REQUEST
-- =====================================================================

create or replace function public.issue_cash_request(
    p_request_id      bigint,
    p_idempotency_key uuid
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    action_name constant text := 'issue_cash_request';
    employee_id bigint;
    employee_role text;
    current_user_id uuid;
    previous_result jsonb;
    request_before public.cash_requests%rowtype;
    request_after public.cash_requests%rowtype;
    recipient_operation public.cash_operations%rowtype;
    financier_operation public.cash_operations%rowtype;
    recipient_name text;
    result jsonb;
begin
    current_user_id := auth.uid();
    employee_id := public.rsk_current_employee_id();
    employee_role := public.rsk_current_employee_role();

    if current_user_id is null or employee_id is null then
        raise exception using errcode = '28000', message = 'Нет активного привязанного сотрудника';
    end if;
    if p_idempotency_key is null then
        raise exception using errcode = '22023', message = 'idempotency_key обязателен';
    end if;
    if employee_role not in ('Администратор', 'Главный инженер', 'Финансист') then
        raise exception using errcode = '42501', message = 'Нет права выдавать деньги по заявке';
    end if;

    perform pg_advisory_xact_lock(hashtextextended(
        current_user_id::text || ':' || action_name || ':' || p_idempotency_key::text, 0
    ));

    select a.new_data -> 'result'
      into previous_result
      from public.audit_log as a
     where a.actor_user_id = current_user_id
       and a.action = action_name
       and a.idempotency_key = p_idempotency_key;
    if previous_result is not null then
        return previous_result;
    end if;

    select r.*
      into request_before
      from public.cash_requests as r
     where r.id = p_request_id
     for update;

    if not found then
        raise exception using errcode = 'P0002', message = 'Финансовая заявка не найдена';
    end if;
    if request_before.status <> 'approved' then
        raise exception using errcode = 'P0001', message = 'Заявка должна быть в статусе "Одобрено"';
    end if;
    if request_before.total_sum is null or request_before.total_sum <= 0 then
        raise exception using errcode = '22023', message = 'Сумма заявки должна быть больше нуля';
    end if;

    select e.name
      into recipient_name
      from public.employees as e
     where e.id = request_before.employee_id
       and coalesce(e.status, 'active') = 'active';
    if not found then
        raise exception using errcode = 'P0001', message = 'Получатель заявки неактивен или не найден';
    end if;

    insert into public.cash_operations (
        employee_id,
        operation_type,
        amount,
        description,
        source,
        operation_date,
        created_by
    ) values (
        request_before.employee_id,
        'issue',
        request_before.total_sum,
        format('Заявка %s — выдача подотчёта', request_before.request_number),
        'cash_request_issue',
        current_date,
        current_user_id
    )
    returning * into recipient_operation;

    if employee_role = 'Финансист' then
        insert into public.cash_operations (
            employee_id,
            operation_type,
            amount,
            description,
            source,
            operation_date,
            created_by
        ) values (
            employee_id,
            'return',
            request_before.total_sum,
            format('Выдача по заявке %s — %s', request_before.request_number, recipient_name),
            'cash_request_debit',
            current_date,
            current_user_id
        )
        returning * into financier_operation;
    end if;

    update public.cash_requests
       set status = 'issued',
           issued_operation_id = recipient_operation.id
     where id = request_before.id
    returning * into request_after;

    result := jsonb_build_object(
        'request_id', request_after.id,
        'request_number', request_after.request_number,
        'status', request_after.status,
        'amount', request_after.total_sum,
        'recipient_operation_id', recipient_operation.id,
        'financier_operation_id', case when employee_role = 'Финансист'
                                       then financier_operation.id else null end
    );

    perform public.rsk_write_audit(
        action_name,
        'cash_requests',
        request_after.id::text,
        p_idempotency_key,
        to_jsonb(request_before),
        jsonb_build_object(
            'result', result,
            'request', to_jsonb(request_after),
            'recipient_operation', to_jsonb(recipient_operation),
            'financier_operation', case when employee_role = 'Финансист'
                                        then to_jsonb(financier_operation) else null end
        ),
        jsonb_build_object('issued_by_role', employee_role)
    );

    return result;
end;
$$;

