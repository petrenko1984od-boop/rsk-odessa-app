--   1. database/migrate-v2.7-rls-finance.sql уже применён;
--   2. frontend переключён на RPC из этого файла;
--   3. только после этого применяется данный файл.
--
-- ВАЖНО: миграция удаляет временные RLS-политики прямой записи Финансиста
-- и Снабженца, а также закрывает прямой INSERT в orders/cash_requests.
-- Старый frontend после применения не сможет создавать заявки, выдавать
-- деньги и сохранять расход своей доставки напрямую.
--
-- RPC:
--   * create_order_with_items          — заявка материалов + позиции;
--   * create_cash_request_with_items   — финансовая заявка + позиции;
--   * issue_cash_request               — обе стороны выдачи + статус заявки;
--   * save_own_delivery_expense        — upsert/delete своей доставки.
--
-- Все функции SECURITY DEFINER, сами проверяют auth.uid(), активного
-- сотрудника, роль, состояние сущности и входные данные. Любая ошибка
-- откатывает всю команду вместе с записью Audit Log.
