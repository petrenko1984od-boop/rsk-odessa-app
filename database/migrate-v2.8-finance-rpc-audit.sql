    c.relname as table_name,
    c.relrowsecurity as rls_enabled,
    c.relforcerowsecurity as rls_forced,
    has_table_privilege('authenticated', 'public.audit_log', 'SELECT') as authenticated_select,
    has_table_privilege('authenticated', 'public.audit_log', 'INSERT') as authenticated_insert,
    has_table_privilege('authenticated', 'public.audit_log', 'UPDATE') as authenticated_update,
    has_table_privilege('authenticated', 'public.audit_log', 'DELETE') as authenticated_delete
