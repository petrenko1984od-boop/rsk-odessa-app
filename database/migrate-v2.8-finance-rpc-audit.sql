-- 2. RPC: CREATE_ORDER_WITH_ITEMS
-- =====================================================================

create or replace function public.create_order_with_items(
    p_project_id      bigint,
    p_section_id      bigint,
    p_desired_date    date,
    p_comment         text,
    p_items           jsonb,
    p_idempotency_key uuid
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    action_name constant text := 'create_order_with_items';
    employee_id bigint;
    employee_role text;
    current_user_id uuid;
    previous_result jsonb;
    normalized_items jsonb := '[]'::jsonb;
    item jsonb;
    item_name text;
    item_unit text;
    item_qty numeric;
    item_count integer;
    current_year integer;
    year_short text;
    number_pattern text;
    max_number bigint;
    request_number text;
    created_order public.orders%rowtype;
    result jsonb;
begin
    current_user_id := auth.uid();
    employee_id := public.rsk_current_employee_id();
    employee_role := public.rsk_current_employee_role();

    if current_user_id is null or employee_id is null then
        raise exception using errcode = '28000', message = 'Нет активного привязанного сотрудника';
    end if;
    if p_idempotency_key is null then
        raise exception using errcode = '22023', message = 'idempotency_key обязателен';
    end if;
    if employee_role not in (
        'Администратор', 'Главный инженер', 'Снабженец', 'Инженер ПТО', 'Прораб'
    ) then
        raise exception using errcode = '42501', message = 'Нет права создавать заявку на материалы';
    end if;

    -- Один actor/action/key выполняется строго один раз, включая параллельный retry.
    perform pg_advisory_xact_lock(hashtextextended(
        current_user_id::text || ':' || action_name || ':' || p_idempotency_key::text, 0
    ));

    select a.new_data -> 'result'
      into previous_result
      from public.audit_log as a
     where a.actor_user_id = current_user_id
       and a.action = action_name
       and a.idempotency_key = p_idempotency_key;
    if previous_result is not null then
        return previous_result;
    end if;

    if p_project_id is null or not exists (
        select 1 from public.projects as p where p.id = p_project_id
    ) then
        raise exception using errcode = '22023', message = 'Объект не найден';
    end if;
    if employee_role = 'Прораб' and not exists (
        select 1 from public.projects as p
        where p.id = p_project_id and p.foreman_id = employee_id
    ) then
        raise exception using errcode = '42501', message = 'Прораб может создавать заявки только по своему объекту';
    end if;
    if p_section_id is null or not exists (
        select 1 from public.sections as s
        where s.id = p_section_id and s.project_id = p_project_id
    ) then
        raise exception using errcode = '22023', message = 'Раздел не принадлежит выбранному объекту';
    end if;
    if p_desired_date is null then
        raise exception using errcode = '22023', message = 'Желаемая дата поставки обязательна';
    end if;
    if p_items is null or jsonb_typeof(p_items) <> 'array' then
        raise exception using errcode = '22023', message = 'Позиции должны быть JSON-массивом';
    end if;

    item_count := jsonb_array_length(p_items);
    if item_count < 1 or item_count > 200 then
        raise exception using errcode = '22023', message = 'В заявке должно быть от 1 до 200 позиций';
    end if;

    for item in select value from jsonb_array_elements(p_items)
    loop
        if jsonb_typeof(item) <> 'object' then
            raise exception using errcode = '22023', message = 'Каждая позиция должна быть объектом';
        end if;

        item_name := btrim(coalesce(item ->> 'name', ''));
        item_unit := btrim(coalesce(item ->> 'unit', 'шт'));
        begin
            item_qty := (item ->> 'qty')::numeric;
        exception when others then
            raise exception using errcode = '22023', message = 'Количество позиции должно быть числом';
        end;

        if item_name = '' or char_length(item_name) > 500 then
            raise exception using errcode = '22023', message = 'Название позиции обязательно и не длиннее 500 символов';
        end if;
        if item_unit = '' or char_length(item_unit) > 20 then
            raise exception using errcode = '22023', message = 'Некорректная единица измерения';
        end if;
        if item_qty::text in ('NaN', 'Infinity', '-Infinity')
           or item_qty <= 0 or item_qty > 1000000000 then
            raise exception using errcode = '22023', message = 'Количество позиции должно быть больше нуля';
        end if;

        normalized_items := normalized_items || jsonb_build_array(jsonb_build_object(
            'name', item_name,
            'unit', item_unit,
            'qty', item_qty
        ));
    end loop;

    current_year := extract(year from current_date)::integer;
    year_short := right(current_year::text, 2);

    perform pg_advisory_xact_lock(hashtextextended('rsk:order-number:' || current_year::text, 0));

    number_pattern := '^№[[:space:]]+([0-9]+)/' || year_short || '$';
    select coalesce(max((matched.parts)[1]::bigint), 0)
      into max_number
      from public.orders as o
      cross join lateral (
          select regexp_match(o.request_number, number_pattern) as parts
      ) as matched
     where matched.parts is not null
       and o.created_at >= make_date(current_year, 1, 1)
       and o.created_at < make_date(current_year + 1, 1, 1);

    request_number := format('№ %s/%s', max_number + 1, year_short);

    insert into public.orders (
        request_number,
        project_id,
        section_id,
        status,
        desired_date,
        purchase_data,
        created_by_employee_id,
        payment_source
    ) values (
        request_number,
        p_project_id,
        p_section_id,
        'new',
        p_desired_date,
        case when nullif(btrim(coalesce(p_comment, '')), '') is null
             then '{}'::jsonb
             else jsonb_build_object('comment', btrim(p_comment)) end,
        employee_id,
        'company'
    )
    returning * into created_order;

    insert into public.order_items (order_id, name, unit, qty)
    select
        created_order.id,
        rows.name,
        rows.unit,
        rows.qty
    from jsonb_to_recordset(normalized_items) as rows(name text, unit text, qty numeric);

    result := jsonb_build_object(
        'order_id', created_order.id,
        'request_number', created_order.request_number,
        'status', created_order.status,
        'items_count', item_count
    );

    perform public.rsk_write_audit(
        action_name,
        'orders',
        created_order.id::text,
        p_idempotency_key,
        null,
        jsonb_build_object(
            'result', result,
            'order', to_jsonb(created_order),
            'items', normalized_items
        ),
        jsonb_build_object('project_id', p_project_id, 'section_id', p_section_id)
    );

    return result;
end;
$$;

