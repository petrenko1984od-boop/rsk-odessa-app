create or replace function public.save_own_delivery_expense(
    p_order_id        bigint,
    p_enabled         boolean,
    p_amount          numeric,
    p_charge          text,
    p_employee_id     bigint,
    p_vat_rate        numeric,
    p_idempotency_key uuid
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    action_name constant text := 'save_own_delivery_expense';
    employee_id bigint;
    employee_role text;
    current_user_id uuid;
    previous_result jsonb;
    order_row public.orders%rowtype;
    old_operation public.cash_operations%rowtype;
    new_operation public.cash_operations%rowtype;
    has_old boolean := false;
    payer_id bigint;
    normalized_rate numeric;
    normalized_amount numeric;
    vat_amount numeric;
    result jsonb;
begin
    current_user_id := auth.uid();
    employee_id := public.rsk_current_employee_id();
    employee_role := public.rsk_current_employee_role();

    if current_user_id is null or employee_id is null then
        raise exception using errcode = '28000', message = 'Нет активного привязанного сотрудника';
    end if;
    if p_idempotency_key is null then
        raise exception using errcode = '22023', message = 'idempotency_key обязателен';
    end if;
    if employee_role not in ('Администратор', 'Снабженец') then
        raise exception using errcode = '42501', message = 'Нет права сохранять расход своей доставки';
    end if;

    perform pg_advisory_xact_lock(hashtextextended(
        current_user_id::text || ':' || action_name || ':' || p_idempotency_key::text, 0
    ));

    select a.new_data -> 'result'
      into previous_result
      from public.audit_log as a
     where a.actor_user_id = current_user_id
       and a.action = action_name
       and a.idempotency_key = p_idempotency_key;
    if previous_result is not null then
        return previous_result;
    end if;

    select o.*
      into order_row
      from public.orders as o
     where o.id = p_order_id
     for update;
    if not found then
        raise exception using errcode = 'P0002', message = 'Заявка на материалы не найдена';
    end if;

    if p_charge not in ('snagach', 'employee', 'firm') then
        raise exception using errcode = '22023', message = 'Некорректный способ оплаты своей доставки';
    end if;

    select operation.*
      into old_operation
      from public.cash_operations as operation
     where operation.order_id = p_order_id
       and operation.source = 'own_delivery'
     for update;
    has_old := found;

    -- Платит фирма, доставка отключена или сумма очищена: расхода подотчёта нет.
    if not coalesce(p_enabled, false)
       or p_charge = 'firm'
       or coalesce(p_amount, 0) <= 0 then
        if has_old then
            delete from public.cash_operations where id = old_operation.id;
        end if;

        result := jsonb_build_object(
            'order_id', p_order_id,
            'operation_id', null,
            'action', case when has_old then 'deleted' else 'unchanged' end,
            'amount', 0
        );

        perform public.rsk_write_audit(
            action_name,
            'cash_operations',
            case when has_old then old_operation.id::text else p_order_id::text end,
            p_idempotency_key,
            case when has_old then to_jsonb(old_operation) else null end,
            jsonb_build_object('result', result, 'operation', null),
            jsonb_build_object('order_id', p_order_id, 'charge', p_charge)
        );
        return result;
    end if;

    normalized_amount := round(p_amount, 2);
    if normalized_amount::text in ('NaN', 'Infinity', '-Infinity')
       or normalized_amount <= 0 or normalized_amount > 1000000000000 then
        raise exception using errcode = '22023', message = 'Сумма доставки должна быть больше нуля';
    end if;

    normalized_rate := least(greatest(coalesce(p_vat_rate, 0), 0), 100);
    if normalized_rate::text in ('NaN', 'Infinity', '-Infinity') then
        normalized_rate := 0;
    end if;
    vat_amount := case when normalized_rate > 0
                       then round(normalized_amount * normalized_rate / (100 + normalized_rate), 2)
                       else 0 end;

    if p_charge = 'employee' then
        payer_id := p_employee_id;
        if payer_id is null or not exists (
            select 1 from public.employees as e
            where e.id = payer_id and coalesce(e.status, 'active') = 'active'
        ) then
            raise exception using errcode = '22023', message = 'Выбранный сотрудник неактивен или не найден';
        end if;
    else
        payer_id := employee_id;
    end if;

    if has_old then
        update public.cash_operations
           set employee_id = payer_id,
               operation_type = 'expense',
               amount = normalized_amount,
               category = 'delivery',
               project_id = order_row.project_id,
               section_id = order_row.section_id,
               order_id = order_row.id,
               items = jsonb_build_array(jsonb_build_object(
                   'name', 'Доставка компании',
                   'unit', 'усл.',
                   'qty', 1,
                   'price', normalized_amount,
                   'sum', normalized_amount
               )),
               vat_rate = normalized_rate,
               vat_amount = vat_amount,
               source = 'own_delivery',
               description = format('Своя доставка по заявке %s', order_row.request_number),
               operation_date = current_date,
               created_by = current_user_id
         where id = old_operation.id
        returning * into new_operation;
    else
        insert into public.cash_operations (
            employee_id,
            operation_type,
            amount,
            category,
            project_id,
            section_id,
            order_id,
            items,
            vat_rate,
            vat_amount,
            source,
            description,
            operation_date,
            created_by
        ) values (
            payer_id,
            'expense',
            normalized_amount,
            'delivery',
            order_row.project_id,
            order_row.section_id,
            order_row.id,
            jsonb_build_array(jsonb_build_object(
                'name', 'Доставка компании',
                'unit', 'усл.',
                'qty', 1,
                'price', normalized_amount,
                'sum', normalized_amount
            )),
            normalized_rate,
            vat_amount,
            'own_delivery',
            format('Своя доставка по заявке %s', order_row.request_number),
            current_date,
            current_user_id
        )
        returning * into new_operation;
    end if;

    result := jsonb_build_object(
        'order_id', p_order_id,
        'operation_id', new_operation.id,
        'action', case when has_old then 'updated' else 'created' end,
        'employee_id', new_operation.employee_id,
        'amount', new_operation.amount,
        'vat_amount', new_operation.vat_amount
    );

    perform public.rsk_write_audit(
        action_name,
        'cash_operations',
        new_operation.id::text,
        p_idempotency_key,
        case when has_old then to_jsonb(old_operation) else null end,
        jsonb_build_object('result', result, 'operation', to_jsonb(new_operation)),
        jsonb_build_object('order_id', p_order_id, 'charge', p_charge)
    );

    return result;
end;
$$;

