as $$
declare
    action_name constant text := 'create_cash_request_with_items';
    employee_id bigint;
    employee_role text;
    current_user_id uuid;
    previous_result jsonb;
    normalized_items jsonb := '[]'::jsonb;
    item jsonb;
    item_name text;
    item_unit text;
    item_qty numeric;
    item_price numeric;
    item_total numeric;
    total_sum numeric := 0;
    item_count integer;
    current_year integer;
    year_short text;
    number_pattern text;
    max_number bigint;
    request_number text;
    created_request public.cash_requests%rowtype;
    result jsonb;
begin
    current_user_id := auth.uid();
    employee_id := public.rsk_current_employee_id();
    employee_role := public.rsk_current_employee_role();

